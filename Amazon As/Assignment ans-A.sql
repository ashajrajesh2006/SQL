-- Find the average product price for each category.
SELECT
    category,
    AVG(price) AS average_price
FROM products
GROUP BY category;

-- List all customers who have purchased a product from the category Electronics. 

SELECT DISTINCT u.*
FROM users u
JOIN orders o
    ON u.user_id = o.user_id
JOIN orderdetails od
    ON o.order_id = od.order_id
JOIN products p
    ON od.product_id = p.product_id
WHERE p.category = 'Electronics';

--  Find the total number of products sold and the total revenue generated for each product.

SELECT 
    products.product_id,
    products.product_name,
    SUM(orderdetails.quantity) AS total_products_sold,
    SUM(orderdetails.quantity * products.price) AS total_revenue
    FROM products
    JOIN orderdetails
    ON products.product_id = orderdetails.product_id
GROUP BY 
    products.product_id,
    products.product_name;
    
