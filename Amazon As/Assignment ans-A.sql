-- List all customers who purchased more than 1 units of any product, including the product name and total quantity purchased. 
SELECT 
    u.user_name AS customer_name,
    p.product_name,
    SUM(od.quantity) AS total_quantity_purchased
FROM users u
JOIN orders o
    ON u.user_id = o.user_id
JOIN orderdetails od
    ON o.order_id = od.order_id
JOIN products p
    ON od.product_id = p.product_id
GROUP BY 
    u.user_id,
    u.user_name,
    p.product_id,
    p.product_name
HAVING SUM(od.quantity) > 1; 

-- Find the total revenue generated by each category along with the category name.
SELECT 
    p.category,
    SUM(od.quantity * p.price) AS total_revenue
FROM products p
JOIN orderdetails od
    ON p.product_id = od.product_id
GROUP BY p.category;